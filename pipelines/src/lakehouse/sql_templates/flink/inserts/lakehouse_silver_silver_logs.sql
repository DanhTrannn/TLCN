INSERT INTO lakehouse.silver.silver_logs
        SELECT
            event_id  as event_id,
            CAST(event_ts AS TIMESTAMP_LTZ(6)) as event_ts,
            CAST(observed_timestamp AS TIMESTAMP_LTZ(6)) as observed_timestamp,
            schema_name  as schema_name,
            schema_version  as schema_version,
            service_name  as service_name,
            service_version  as service_version,
            service_env  as service_environment,
            service_instance_id as service_instance_id,
            severity_number as severity_number,
            severity_text as severity_text,
            CASE WHEN trace_id = '' THEN CAST(NULL AS STRING) ELSE trace_id END as trace_id,
            CASE WHEN span_id = '' THEN CAST(NULL AS STRING) ELSE span_id END as span_id,
            event_name as event_name,
            event_category as event_category,
            event_kind as event_kind,
            event_outcome as event_outcome,
            duration_ns as event_duration_ns,
            http_method as http_request_method,
            http_route as http_route,
            http_status as http_status_code,
            event_id  as request_id,
            actor_type as actor_type,
            CASE WHEN actor_key = '' THEN CAST(NULL AS STRING) ELSE actor_key END as actor_key,
            client_user_agent as client_user_agent,
            action as ecommerce_action,
            CASE WHEN product_key = '' THEN CAST(NULL AS STRING) ELSE product_key END as ecommerce_product_key,
            CASE WHEN variant_key = '' THEN CAST(NULL AS STRING) ELSE variant_key END as ecommerce_variant_key,
            CASE WHEN search_query = '' THEN CAST(NULL AS STRING) ELSE search_query END as ecommerce_search_query,
            search_redacted as ecommerce_search_redacted,
            CAST(NULL AS MAP<STRING, STRING>) as ecommerce_filters,
            CASE WHEN error_code = '' THEN CAST(NULL AS STRING) ELSE error_code END as error_code,
            CASE WHEN error_type = '' THEN CAST(NULL AS STRING) ELSE error_type END as error_type,
            data_origin as data_origin,
            CAST(ingest_ts AS TIMESTAMP_LTZ(6)) as _silver_ingested_at,
            'flink-streaming-job' as _source_bronze_run_id
        FROM raw_events_view
